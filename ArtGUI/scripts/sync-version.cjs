'use strict';

const fs = require('node:fs');
const path = require('node:path');

// package.json is the only hand-edited ArtGUI release version.
function syncVersion(root = path.resolve(__dirname, '..'), {check = false} = {}) {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const version = JSON.parse(read('package.json')).version;
  const numeric = '(0|[1-9][0-9]*)';
  const identifier = '(?:0|[1-9][0-9]*|[0-9]*[A-Za-z-][0-9A-Za-z-]*)';
  const semver = new RegExp(`^${numeric}\\.${numeric}\\.${numeric}(?:-${identifier}(?:\\.${identifier})*)?(?:\\+[0-9A-Za-z-]+(?:\\.[0-9A-Za-z-]+)*)?$`);
  if (typeof version !== 'string' || !semver.test(version)) throw Error('package.json must contain a valid SemVer version.');
  const pending = [];
  function plan(file, updated) {
    const previous = fs.existsSync(path.join(root, file)) ? read(file) : null;
    if (previous !== updated) pending.push([file, updated]);
  }
  function replaceVersion(file, section) {
    const original = read(file);
    let found = false;
    const updated = original.replace(section, block => {
      if (!/^version\s*=\s*"[^"]*"/m.test(block)) throw Error(`Missing application version in ${file}.`);
      found = true;
      return block.replace(/^(version\s*=\s*)"[^"]*"/m, `$1"${version}"`);
    });
    if (!found) throw Error(`Missing application package in ${file}.`);
    plan(file, updated);
  }
  replaceVersion('src-tauri/Cargo.toml', /^\[package\]\r?\n[\s\S]*?(?=^\[|$(?![\s\S]))/m);
  replaceVersion('src-tauri/Cargo.lock', /^\[\[package\]\]\r?\nname = "artisan-workbench"\r?\n[\s\S]*?(?=^\[\[package\]\]|$(?![\s\S]))/m);
  const lockText = read('package-lock.json');
  const lock = JSON.parse(lockText);
  if (!lock.packages?.['']) throw Error('Missing root package in package-lock.json.');
  if (lock.version !== version || lock.packages[''].version !== version) {
    lock.version = version;
    lock.packages[''].version = version;
    plan('package-lock.json', JSON.stringify(lock, null, 2) + '\n');
  }
  plan('ui/version.js', '// Generated by scripts/sync-version.cjs from package.json; do not edit.\n'
    + `export const ARTGUI_VERSION = ${JSON.stringify(version)};\n`);
  if (check && pending.length) throw Error(`ArtGUI version files are stale: ${pending.map(([file]) => file).join(', ')}. Run npm run sync-version.`);
  for (const [file, updated] of pending) fs.writeFileSync(path.join(root, file), updated);
  return version;
}

module.exports = {syncVersion};
if (require.main === module) {
  try { console.log(`ArtGUI version ${syncVersion(undefined, {check: process.argv.includes('--check')})}`); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
