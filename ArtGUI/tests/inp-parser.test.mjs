import assert from 'node:assert/strict';
import {parseInp} from '../ui/inp-parser.mjs';
const nodeText='*NODE\n10,0,0,0\n20,1,0,0\n30,0,1,0\n40,0,0,1\n50,0,0,-1\n';
const mesh=parseInp(nodeText+'*ELEMENT,TYPE=C3D4\n100,10,20,30,40\n200,10,30,20,50');
assert.equal(mesh.metadata.surfaceTriangles,6,'shared tetrahedral face removed');
assert.equal(mesh.metadata.nodeCount,5);assert.equal(mesh.topology.elements[1].id,200);
assert.deepEqual([...mesh.topology.nodeIds],[10,20,30,40,50]);
const mixed=parseInp(nodeText+'*ELEMENT,TYPE=B31H,ELSET=Beams\n1,10,20\n*ELEMENT,TYPE=R3D3\n2,10,20,30');
assert.equal(mixed.lines.length,6);assert.equal(mixed.positions.length,9);assert.deepEqual(mixed.metadata.elementSets,['Beams']);
const beam=parseInp('*Node\n1,1D2,2D2\n2,101,200\n*Element,type=T3D2\n1,1,\n2');
assert.deepEqual(beam.center,[100.5,200,0]);assert.equal(beam.positions.length,0);assert.equal(beam.lines.length,6);
const boxNodes='*NODE\n1,0,0,0\n2,1,0,0\n3,1,1,0\n4,0,1,0\n5,0,0,1\n6,1,0,1\n7,1,1,1\n8,0,1,1\n';
const hex=parseInp(boxNodes+'*ELEMENT,TYPE=C3D8RH\n1,1,2,3,4,\n5,6,7,8');
assert.equal(hex.positions.length/9,12);assert.equal(hex.edges.length/6,12,'hexahedron edges exclude triangle diagonals');
const quad=parseInp(boxNodes+'*ELEMENT,TYPE=CAX4P\n1,1,2,3,4');
assert.equal(quad.positions.length/9,2);assert.equal(quad.edges.length/6,4);
const wedge=parseInp(boxNodes+'*ELEMENT,TYPE=C3D6\n1,1,2,4,5,6,8');
assert.equal(wedge.positions.length/9,8);assert.equal(wedge.edges.length/6,9);
for(const text of [nodeText+'*ELEMENT,TYPE=C3D10\n1,10,20,30,40',nodeText+'*ELEMENT,TYPE=B31\n1,10,99',nodeText+'*INCLUDE,INPUT=extra.inp',nodeText+'*INSTANCE,NAME=test',nodeText+'*SYSTEM',nodeText+'*ELEMENT,TYPE=B31\n1,10',nodeText+'*NODE\n10,1,2,3'])assert.throws(()=>parseInp(text));
console.log('PASS: shared-face removal, original IDs/connectivity, mixed beams/surfaces, 2D and D exponents, continuation lines, and malformed/unsupported input rejection.');
